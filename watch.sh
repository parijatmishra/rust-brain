#!/usr/bin/env bash
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

# _run_once SCRIPT: run SCRIPT and report the outcome.
# Inside `if`, a failure does not trip set -e and stop the watcher.
_run_once() {
  echo; echo; echo; echo "*** $(date +%T)"
  if "$1"; then
    echo "=== PASSED"
  else
    echo "=== FAILED (exit $?)"
  fi
}

# Check that `fswatch` is available
command -v fswatch >/dev/null || (echo "fswatch not found (brew install fswatch)" >&2; exit 1)
SCRIPT=./book_build.sh
# Check that book_build.sh is present and executable
[[ -x "$SCRIPT" ]] || (echo "missing or not executable: $SCRIPT" >&2; exit 2)

# On Ctrl+C/TERM, kill the whole process group (fswatch and any running
# SCRIPT).
trap 'trap - INT TERM; kill 0' INT TERM

# Always execute SCRIPT at startup
_run_once $SCRIPT

# Look for file modifications, and run SCRIPT
# fswatch -o prints one event count per batch (--latency = batch window, s).
# The inner loop drains batches until 1s of quiet, so an edit burst, or edits
# made while SCRIPT runs, yield a single re-run. Integer -t keeps bash 3.2
# working. Process substitution keeps the loop in the main shell, so the trap
# fires promptly while waiting for events.
# Paths excluded from fswatch:
# - '\.sw[a-px]$', '~$', '/4913$': temp files created by `vim`
# - '/target(/|$)': output generated by `cargo`
# - '/html': output generated by `mdbook`
# - '\.log$': command output
# - `\.tmp`: temp files
while read -r events; do
  while read -r -t 1 batch; do events=$((events + batch)); done
  _run_once $SCRIPT
done < <(fswatch -o --latency 0.5 --recursive --extended \
            --exclude '\.git' \
            --exclude '\.sw[a-px]$' --exclude '~$' --exclude '/4913$' \
            --exclude '/target(/|$)' \
            --exclude '/html(/|$)' \
            --exclude '\.log$' \
            --exclude '\.tmp' \
            --event Updated --event Created --event Removed --event Renamed .)
